import { Buffer } from 'node:buffer';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) {
  throw new Error('Usage: node scripts/build.mjs [--check]');
}
const root = fileURLToPath(new URL('../', import.meta.url));
const assetPath = join(root, 'assets/server.bin');
const manifestPath = join(root, 'src/manifest.ts');
const require = createRequire(import.meta.url);
// pnpm keeps Photon among pi-durable's own dependencies; the bundle embeds the copy pi-durable's processor loads.
const durable = require.resolve('@earendil-works/pi-durable/package.json');
const photon = createRequire(durable).resolve('@silvia-odwyer/photon/photon_rs_bg.wasm');
// pi-ai exports no package.json, so each version is read from the app's own direct dependency.
const version = async (name) =>
  JSON.parse(await readFile(join(root, 'node_modules', name, 'package.json'), 'utf8')).version;
const pi = {
  durable: await version('@earendil-works/pi-durable'),
  ai: await version('@earendil-works/pi-ai'),
  chord: await version('@earendil-works/chord'),
};

const { outputFiles } = await build({
  entryPoints: [join(root, 'src/main.ts')],
  // Paths in the bundle's comments are relative to this, so every checkout builds the same bytes.
  absWorkingDir: root,
  outfile: 'server.js',
  write: false,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  loader: { '.wasm': 'binary' },
  alias: { '@silvia-odwyer/photon/photon_rs_bg.wasm': photon },
  define: { INFINICHAT_PI: JSON.stringify(pi) },
  // Some SDKs pi-ai bundles call require(), which an ES module lacks (pi-ai README, "Bundling and Tree Shaking").
  banner: { js: 'import { createRequire } from "node:module";const require = createRequire(import.meta.url);' },
  logLevel: 'warning',
});
const bytes = outputFiles[0].contents;
const entry = { sha256: createHash('sha256').update(bytes).digest('hex'), size: bytes.byteLength, pi };
const manifest = '// Generated by scripts/build.mjs. Do not edit by hand.\n'
  + `export const INFINICHAT_SERVER_MANIFEST = ${JSON.stringify(entry, null, 2)} as const;\n`;
if (check) {
  const asset = await readFile(assetPath).catch(() => Buffer.alloc(0));
  if (!asset.equals(bytes) || await readFile(manifestPath, 'utf8').catch(() => '') !== manifest) {
    throw new Error('The InfiniChat server asset is stale. Run node scripts/build.mjs.');
  }
} else {
  await mkdir(join(root, 'assets/infinichat-server'), { recursive: true });
  await writeFile(assetPath, bytes);
  await writeFile(manifestPath, manifest);
}
console.log(`${check ? 'Verified' : 'Built'} the InfiniChat server asset (${entry.size} bytes, ${entry.sha256}).`);
