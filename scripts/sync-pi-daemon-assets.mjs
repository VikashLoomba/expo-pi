import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// The npm artifact is pinned independently of mutable registry metadata.
const version = '1.2.0';
const integrity = 'sha512-+/AQGowCXb0rawNeeWmZwy8PN7MpeBeqAiQ1RMjgUWL4gtu4KXLQklIzyvaPoGncRb4F0GTXc57JbuGKQWnvUQ==';
const tarball = `https://registry.npmjs.org/@earendil-works/pi-env/-/pi-env-${version}.tgz`;
const targets = ['darwin-arm64', 'darwin-x64', 'linux-arm64', 'linux-x64'];
const root = fileURLToPath(new URL('../', import.meta.url));
const assets = join(root, 'assets/pi-env');
const manifestPath = join(root, 'src/pi/execution/remote/daemon-manifest.ts');
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/sync-pi-daemon-assets.mjs [--check]');

const entries = {};
let temporary;
try {
  if (!check) {
    temporary = await mkdtemp(join(tmpdir(), 'pi-daemon-assets-'));
    const response = await fetch(tarball);
    if (!response.ok) throw new Error(`Could not retrieve pinned Pi daemon package (${response.status}).`);
    const archive = Buffer.from(await response.arrayBuffer());
    const actual = `sha512-${createHash('sha512').update(archive).digest('base64')}`;
    if (actual !== integrity) throw new Error('Pi daemon package integrity mismatch; no assets were changed.');
    const archivePath = join(temporary, 'package.tgz');
    await writeFile(archivePath, archive);
    await mkdir(assets, { recursive: true });
    for (const target of targets) {
      const bytes = execFileSync('tar', ['-xOf', archivePath, `package/bin/pi-env-${target}/pi-env`], { maxBuffer: 4 * 1024 * 1024 });
      await writeFile(join(assets, `pi-env-${target}.bin`), bytes);
    }
  }
  for (const target of targets) {
    const bytes = await readFile(join(assets, `pi-env-${target}.bin`));
    entries[target] = { sha256: sha256(bytes), size: bytes.byteLength };
  }
  const manifest = '// Generated by scripts/sync-pi-daemon-assets.mjs. Do not edit hashes by hand.\n'
    + `export const PI_DAEMON_VERSION = '${version}';\n`
    + `export const PI_DAEMON_PACKAGE_INTEGRITY = '${integrity}';\n`
    + `export const PI_DAEMON_MANIFEST = ${JSON.stringify(entries, null, 2)} as const;\n`;
  if (check) {
    if (await readFile(manifestPath, 'utf8') !== manifest) throw new Error('Bundled Pi daemon assets do not match their pinned manifest.');
  } else await writeFile(manifestPath, manifest);
  console.log(`${check ? 'Verified' : 'Updated'} ${targets.length} pinned Pi Env ${version} assets (${Object.values(entries).reduce((n, entry) => n + entry.size, 0)} bytes).`);
} finally {
  if (temporary) await rm(temporary, { recursive: true, force: true });
}
